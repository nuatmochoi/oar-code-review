"""Frozen wire-schema builder; dynamic enums are mechanical source/target IDs.

Source/field quotes are extracted by the controller, never regenerated by the
judge. Labels and semantic relevance criteria are unchanged from reviewbench48.
"""
from schemas import obj,arr,S,I,enum,NULLABLE_BOOL
LABELS=('target_correct','target_wrong_cause','other_confirmed_defect','false','unresolved','duplicate_target','duplicate_other','structure_failure')
CORE_FIELDS=('title','explanation','trigger','impact','none')

def judge_schema(truth,source_packet,finding_count):
 source_ids=[s['id']for s in source_packet['sources']]
 # Empty source pool permits no assessments; unsupported semantic labels still
 # fail the unchanged annotation validator. A fake source is never fabricated.
 source_id=enum(*source_ids)if source_ids else enum('__NO_SOURCE_AVAILABLE__')
 assessment=obj(dict(source_id=source_id,start_line={'type':'integer','minimum':1},end_line={'type':'integer','minimum':1},judgment=enum('supports','refutes','unresolved'),reason=S))
 finding=obj(dict(finding_index={'type':'integer','enum':list(range(finding_count))},label=enum(*LABELS),matched_target_id=enum('',*(t['id']for t in truth['targets'])),cause_correct={'type':'boolean'},regression_anchor_relevant=NULLABLE_BOOL,failure_operation_relevant=NULLABLE_BOOL,evidence_relevant=NULLABLE_BOOL,core_field=enum(*CORE_FIELDS),source_assessments=arr(assessment),reason=S))
 return obj(dict(findings=arr(finding),source_limitations=arr(S),reasoning=S))
